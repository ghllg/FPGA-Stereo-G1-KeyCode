"""Translate the shared metadata validator to kernel-compatible C mechanically."""
import hashlib
import json
import re
from pathlib import Path


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def main():
    root=Path(__file__).resolve().parent
    source=root.parents[1]/'inference/hls/stream_region_program.h'
    text=source.read_text()
    text=text.replace('#pragma once\n#include <stdint.h>\n#include <stddef.h>\n#include <string.h>',
        '#ifndef U02_REGION_PROGRAM_VALIDATION_H\n#define U02_REGION_PROGRAM_VALIDATION_H\n'
        '#include "u02_region_model_validation.h"\n#ifdef __KERNEL__\n#include <linux/string.h>\n#else\n#include <string.h>\n#endif')
    constants={'REGION_MAGIC':'0x52323055u','REGION_VERSION':'1u','REGION_NONE':'0xffffffffu',
        'REGION_MAX_TENSORS':'128u','REGION_MAX_COMMANDS':'64u','REGION_MAX_ARENA':'2097152u'}
    text=re.sub(r'static const uint32_t [^;]+;', '', text)
    text='\n'.join('#define '+name+' '+value for name,value in constants.items())+'\n'+text
    for name in ('RegionHeader','RegionTensor','RegionCommand'):
        text=text.replace('struct '+name+' {','typedef struct '+name+' {')
        pattern=r'(typedef struct '+name+r' \{[^}]+)\};'
        text=re.sub(pattern,lambda m:m[1]+'} '+name+';',text)
    text=text.replace('static_assert(','U02R_STATIC_ASSERT(')
    text=text.replace('enum RegionOpcode',
        '#ifdef __cplusplus\n#define U02R_STATIC_ASSERT static_assert\n#else\n#define U02R_STATIC_ASSERT _Static_assert\n#endif\nenum RegionOpcode')
    text=text.replace('const RegionTensor& a,const RegionTensor& b','const RegionTensor* a,const RegionTensor* b')
    text=text.replace('static_cast<const unsigned char*>(raw)','(const unsigned char*)raw')
    text=re.sub(r'const auto& (\w+)=tensors\[([^\]]+)\]',r'const RegionTensor* \1=&tensors[\2]',text)
    for name in ('a','b','t','root','o','p'):
        text=re.sub(r'\b'+name+r'\.',name+'->',text)
    text=re.sub(r'uint64_t\(([^()]*)\)',r'((u02r_u64)(\1))',text)
    text=text.replace('uint32_t','u02r_u32').replace('uint64_t','u02r_u64')
    text=text.replace('inline bool','static inline int').replace('inline int region_validate','static inline int region_validate')
    text=text.replace('size_t bytes) {\n#ifndef __SYNTHESIS__','size_t bytes,struct u02_region_validation_workspace* workspace) {\n#ifndef __SYNTHESIS__')
    text=text.replace('if(!raw)return -1;','if(!raw || !workspace)return -1;')
    text=text.replace('RegionTensor tensors[REGION_MAX_TENSORS];bool ready[REGION_MAX_TENSORS]={};',
        'RegionTensor* tensors=workspace->tensors;unsigned char* ready=workspace->ready;\n    memset(ready,0,REGION_MAX_TENSORS);')
    text=text.replace('bool groups[110]={};unsigned streams=0;',
        'unsigned char* groups=workspace->groups;unsigned streams=0;memset(groups,0,110);')
    text=text.replace('true','1').replace('false','0')
    text=text.replace('region_overlap(t,tensors[j])','region_overlap(t,&tensors[j])').replace('region_overlap(o,tensors[j])','region_overlap(o,&tensors[j])')
    workspace='struct u02_region_validation_workspace {RegionTensor tensors[128];unsigned char ready[128],groups[110];};\n'
    text=text.replace('// Validates a private, stable metadata snapshot.',workspace+'\n// Validates a private, stable metadata snapshot.')
    for name in constants:
        text=text.replace(name,'U02R_'+name)
    text=re.sub(r'\bREGION_(ALIAS|CONCAT|SHUFFLE|STREAM)\b',r'U02R_REGION_\1',text)
    for name in ('RegionHeader','RegionTensor','RegionCommand','RegionOpcode'):
        text=text.replace(name,'U02r'+name)
    text=text.replace('region_overlap','u02r_region_overlap').replace('region_validate(','u02_region_program_validate(')
    assert 'auto' not in text and 'uint64_t(' not in text and 'const RegionTensor&' not in text
    # The explicit heap workspace avoids a >4 KiB automatic kernel stack frame.
    text='// Generated by generate_region_program_validation.py; do not hand-edit.\n'+text+'\n#endif\n'
    output=root/'u02_region_program_validation.h';output.write_text(text)
    output.with_suffix('.manifest.json').write_text(json.dumps(dict(source_sha256={str(p):sha(p) for p in (source,Path(__file__))},
        output_sha256=sha(output),scope='Mechanical C translation; integer metadata checks; caller-allocated workspace'),indent=2)+'\n')
    print('U02_REGION_C_PROGRAM',output)


if __name__=='__main__':main()
