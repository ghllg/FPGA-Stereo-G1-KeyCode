"""Derive an isolated shared compute function from the formal FP32 HLS source."""
import argparse
import json
from pathlib import Path
from lower_stream_region import U02, sha


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    source=U02/'inference/hls/stream_overlap_fp32_output.cpp'
    original=source.read_text()
    text='\n'.join(line for line in original.splitlines() if not line.startswith('#pragma HLS INTERFACE'))+'\n'
    replacements={
        'uint64_t* results':'float* results',
        'extern "C" int u02_stream(const uint64_t* a,const uint64_t* b,uint64_t* c,int m,int n,int k)':
            'static int region_shared_compute(const uint64_t* a,const uint64_t* b,float* c,int m,int n,int k)',
        'results[((channels+lane)*plane+start)/2+i]=final[lane][i];':
            'const uint64_t word=final[lane][i];\n                const int at=(channels+lane)*plane+start+i*2;\n                results[at]=output_float(uint32_t(word));\n                results[at+1]=output_float(uint32_t(word>>32));'
    }
    for before,after in replacements.items():
        expected=2 if before=='uint64_t* results' else 1
        if text.count(before)!=expected:raise ValueError('Compute source structure changed: '+before)
        text=text.replace(before,after)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('// Generated by generate_region_compute.py; do not hand-edit.\n'+text)
    Path(str(args.output)+'.manifest.json').write_text(json.dumps(dict(
        source_sha256={str(p):sha(p) for p in (source,Path(__file__))},
        output_sha256=sha(args.output),
        changes='Strip top-only interface pragmas, rename function, unpack identical FP32 output bits into float DDR arena',
        hardware_verified=False),indent=2)+'\n')
    print('U02_REGION_SHARED_COMPUTE',args.output)


if __name__=='__main__':main()
